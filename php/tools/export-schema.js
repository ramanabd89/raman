// Builds the MySQL schema + starter data for the PHP version from a fresh database made by the Node version,
// so both versions always have the same tables and the same demo products / settings.
//   node php/tools/export-schema.js <path-to-fresh-store.db> <fresh-uploads-dir>
// Writes php/install/schema.sql, php/install/seed.sql and copies the demo images to php/app/uploads.
const fs = require('fs');
const path = require('path');
const { DatabaseSync } = require('node:sqlite');

const [dbPath, upDir] = process.argv.slice(2);
if (!dbPath) { console.error('usage: node export-schema.js store.db uploads'); process.exit(1); }
const db = new DatabaseSync(dbPath);
const OUT = path.join(__dirname, '..', 'src', 'app', 'install');
const q = (n) => `\`${n}\``;

// columns that are indexed / unique / keys → VARCHAR(191) (utf8mb4 index limit)
const indexed = new Set();
const uniques = []; const indexes = [];
const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").all();
for (const t of tables) {
  for (const ix of db.prepare(`PRAGMA index_list(${t.name})`).all()) {
    const cols = db.prepare(`PRAGMA index_info(${ix.name})`).all().map((c) => c.name);
    cols.forEach((c) => indexed.add(`${t.name}.${c}`));
    if (ix.origin === 'pk') continue;
    (ix.unique ? uniques : indexes).push({ table: t.name, name: ix.origin === 'u' ? `uq_${t.name}_${cols.join('_')}` : ix.name, cols });
  }
  for (const c of db.prepare(`PRAGMA table_info(${t.name})`).all()) if (c.pk) indexed.add(`${t.name}.${c.name}`);
}

const SHORT = /^(role|status|type|method|color|payment_method|quality|author|purpose|extra_status|reason|source|category)$/;
function colDef(t, c, autoInc) {
  const id = `${t.name}.${c.name}`;
  const ty = String(c.type).toUpperCase();
  let def = '';
  let dflt = c.dflt_value;
  if (ty === 'INTEGER') {
    def = autoInc ? 'BIGINT NOT NULL AUTO_INCREMENT' : 'BIGINT';
  } else if (ty === 'REAL') {
    def = 'DOUBLE';
  } else if (dflt && /datetime\('now'\)/.test(dflt)) {
    def = 'DATETIME'; dflt = 'CURRENT_TIMESTAMP';
  } else if (/^(created_at|updated_at|reminded_at)$/.test(c.name)) {
    def = 'DATETIME';
  } else if (indexed.has(id) || SHORT.test(c.name)) {
    def = 'VARCHAR(191)';
  } else {
    def = 'TEXT';
  }
  if (!autoInc && c.notnull) def += ' NOT NULL';
  if (dflt != null && !autoInc) {
    if (dflt === 'CURRENT_TIMESTAMP') def += ' DEFAULT CURRENT_TIMESTAMP';
    else if (def.startsWith('TEXT')) def += ` DEFAULT (${dflt})`; // MySQL 8.0.13+ / MariaDB 10.2+
    else def += ` DEFAULT ${dflt}`;
  }
  return `  ${q(c.name)} ${def}`;
}

let schema = '-- RamanPhone — MySQL / MariaDB schema (generated by php/tools/export-schema.js)\nSET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n';
for (const t of tables) {
  const cols = db.prepare(`PRAGMA table_info(${t.name})`).all();
  const pks = cols.filter((c) => c.pk).sort((a, b) => a.pk - b.pk);
  const autoInc = pks.length === 1 && /AUTOINCREMENT/i.test(t.sql);
  const lines = cols.map((c) => colDef(t, c, autoInc && c.pk === 1));
  if (pks.length) lines.push(`  PRIMARY KEY (${pks.map((c) => q(c.name)).join(', ')})`);
  for (const u of uniques.filter((x) => x.table === t.name)) lines.push(`  UNIQUE KEY ${q(u.name)} (${u.cols.map(q).join(', ')})`);
  for (const ix of indexes.filter((x) => x.table === t.name)) lines.push(`  KEY ${q(ix.name)} (${ix.cols.map(q).join(', ')})`);
  for (const fk of db.prepare(`PRAGMA foreign_key_list(${t.name})`).all()) {
    lines.push(`  CONSTRAINT ${q(`fk_${t.name}_${fk.from}`)} FOREIGN KEY (${q(fk.from)}) REFERENCES ${q(fk.table)} (${q(fk.to)}) ON DELETE ${fk.on_delete === 'NO ACTION' ? 'RESTRICT' : fk.on_delete}`);
  }
  schema += `CREATE TABLE IF NOT EXISTS ${q(t.name)} (\n${lines.join(',\n')}\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n\n`;
}
schema += 'SET FOREIGN_KEY_CHECKS = 1;\n';
fs.writeFileSync(path.join(OUT, 'schema.sql'), schema);

// starter data: everything except people, sessions and logs
const SKIP = new Set(['users', 'sessions', 'otp_codes', 'auth_failures', 'page_views', 'admin_log', 'login_tickets', 'carts']);
const lit = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' || typeof v === 'bigint' ? String(v) : `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`);
let seed = '-- RamanPhone — starter data (demo products, categories, repair prices, settings)\nSET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\n\n';
for (const t of tables) {
  if (SKIP.has(t.name)) continue;
  const rows = db.prepare(`SELECT * FROM ${t.name}`).all();
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  for (let i = 0; i < rows.length; i += 50) {
    seed += `INSERT INTO ${q(t.name)} (${cols.map(q).join(', ')}) VALUES\n${rows.slice(i, i + 50).map((r) => `(${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')};\n`;
  }
  seed += '\n';
}
seed += 'SET FOREIGN_KEY_CHECKS = 1;\n';
fs.writeFileSync(path.join(OUT, 'seed.sql'), seed);

if (upDir) {
  const dest = path.join(__dirname, '..', 'src', 'uploads');
  fs.mkdirSync(dest, { recursive: true });
  for (const f of fs.readdirSync(upDir)) if (/\.svg$/.test(f)) fs.copyFileSync(path.join(upDir, f), path.join(dest, f));
}
console.log('schema.sql + seed.sql written');
